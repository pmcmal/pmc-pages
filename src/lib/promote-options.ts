/**
 * Dobiera ikone i kolor na podstawie tego, co wiadomo o apce.
 * Gdy nic nie pasuje, zwraca neutralna propozycje - i tak mozna ja zmienic recznie.
 */
export function suggestTile(...texts: (string | undefined)[]): { icon: string; color: ColorOption } {
  const haystack = texts.filter(Boolean).join(" ");
  for (const hint of TILE_HINTS) {
    if (hint.pattern.test(haystack)) return { icon: hint.icon, color: hint.color };
  }
  return { icon: "Sparkles", color: "sky" };
}
